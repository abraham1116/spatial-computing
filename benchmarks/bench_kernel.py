"""TEST — portable kernels: one source, CPU vs Metal. For each case: time every device for real, and
check whether the planner (which only runs reduced probes) picks the really fastest one."""
from __future__ import annotations

import time

from common import save
from spatial.compute import workloads
from spatial.unified import Job, Objective, Planner

CASES = [("pk_mandel", {"n": 64, "iters": 200}), ("pk_mandel", {"n": 512, "iters": 300}), ("pk_mandel", {"n": 2048, "iters": 400}),
         ("pk_collatz", {"n": 64, "limit": 500}), ("pk_collatz", {"n": 512, "limit": 1000}), ("pk_collatz", {"n": 1536, "limit": 2000}),
         ("pk_batch_score", {"n": 64, "signals": 16}), ("pk_batch_score", {"n": 512, "signals": 32}), ("pk_batch_score", {"n": 2048, "signals": 64})]
WL = {"pk_mandel": {"cpu": "pk_mandel_cpu", "gpu_metal": "pk_mandel_metal"}, "pk_collatz": {"cpu": "pk_collatz_cpu", "gpu_metal": "pk_collatz_metal"},
      "pk_batch_score": {"cpu": "pk_batch_score_cpu", "gpu_metal": "pk_batch_score_metal"}}


def real(wname, params):
    workloads.run(wname, **{**params, "n": 8})
    best = float("inf")
    for _ in range(3):
        t = time.perf_counter(); workloads.run(wname, **params); best = min(best, time.perf_counter() - t)
    return best


def main():
    pl, rows, right = Planner(), [], 0
    for fam, params in CASES:
        measured = {v: real(w, params) for v, w in WL[fam].items()}
        plan = pl.plan(Job.compute(fam, **params), Objective())
        best = min(measured, key=measured.get)
        row = {"family": fam, "params": params, "measured_s": measured, "best": best, "chosen": plan.chosen.name,
               "regret": measured[plan.chosen.name] / measured[best]}
        right += row["chosen"] == best
        rows.append(row)
        print(f"{fam:<11}{str(params):<34} " + "  ".join(f"{k} {v * 1e3:9.1f} ms" for k, v in measured.items())
              + f"   best {best:<9} chosen {plan.chosen.name:<9} regret {row['regret']:.2f}x", flush=True)
    out = {"rows": rows, "correct": right, "cases": len(rows), "mean_regret": sum(r["regret"] for r in rows) / len(rows),
           "note": "CUDA C is generated by the same kernels but has never been compiled or run (no NVIDIA hardware)."}
    print(f"planner right {right}/{len(rows)}, mean regret {out['mean_regret']:.2f}x")
    save("kernel", out)


if __name__ == "__main__":
    main()
